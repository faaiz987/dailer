const DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"];

function hoursFor(open: string, close: string, closedDays: string[] = []): Record<string, string> {
  const out: Record<string, string> = {};
  DAYS.forEach((day, i) => {
    out[`openingHours/${i}/day`] = day;
    out[`openingHours/${i}/hours`] = closedDays.includes(day) ? "Closed" : `${open}–${close}`;
  });
  return out;
}

function dist(five: number, four: number, three: number, two: number, one: number) {
  return {
    "reviewsDistribution/fiveStar": String(five),
    "reviewsDistribution/fourStar": String(four),
    "reviewsDistribution/threeStar": String(three),
    "reviewsDistribution/twoStar": String(two),
    "reviewsDistribution/oneStar": String(one),
  };
}

