function toRow(input: SampleInput): Record<string, string> {
  const values: Record<string, string> = {
    ...BASE,
    ...input.distribution,
    ...(input.hours ?? hoursFor("9 AM", "5 PM")),
    title: input.duplicateLabel ?? input.title,
    categoryName: input.categoryName,
    placeId: input.placeId,
    phone: input.phone,
    phoneUnformatted: input.phone.replace(/\D/g, ""),
    countryCode: "US",
    address: input.address,
    street: input.street,
    city: input.city,
    state: input.state,
    postalCode: input.zip,
    neighborhood: input.neighborhood,
    totalScore: input.rating,
    reviewsCount: input.reviews,
    claimThisBusiness: input.claimed,
    permanentlyClosed: input.permanentlyClosed ?? input.closed ?? "FALSE",
    temporarilyClosed: "FALSE",
    price: input.price ?? "",
    website: input.website ?? "",
    description: input.description ?? "",
    ownerDescription: input.ownerDescription ?? "",
    rank: String(input.rank),
    "location/lat": input.lat,
    "location/lng": input.lng,
    url: `https://www.google.com/maps/place/?q=place_id:${input.placeId}`,
    searchString: `${input.categoryName} in ${input.city}, ${input.state}`,
    scrapedAt: "2026-10-18T14:22:00Z",
    language: "en",
    imagesCount: String(10 + (input.rank % 17)),
  };
  if (!values["openingHours/0/hours"]) {
    // keep day labels if a partial hours object was provided
    for (let i = 0; i < 7; i++) values[`openingHours/${i}/day`] = DAYS[i];
  }
  return values;
}

export function createSampleCsv(): string {
  const rows = SAMPLES.map(toRow);
  // A duplicate placeId to demonstrate the import dedupe.
  rows.push({
    ...toRow(SAMPLES[0]),
    title: "Radio Coffee & Beer (duplicate export row)",
    rank: "99",
  });
  return Papa.unparse(rows, { columns: EXPECTED_COLUMNS });
}

